import { chromium } from 'playwright';
import { mkdirSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const base = process.env.STATUS_SMOKE_URL || 'http://127.0.0.1:3041';
const out = process.argv[2];
if (!out) throw new Error('usage: node scripts/smoke-data-status.mjs OUTPUT_DIRECTORY');
mkdirSync(`${out}/screenshots`, { recursive: true });
const browser = await chromium.launch({ headless: true });
const results = [];
try {
  for (const [name, viewport] of [['desktop', {width:1440,height:1000}], ['mobile', {width:390,height:844}]]) {
    const context = await browser.newContext({ viewport, reducedMotion: 'reduce', acceptDownloads: true });
    // Offline saved-price smoke: deliberately block live market/research collection, never synthesize market values.
    await context.route('**/api/**', route => route.abort('blockedbyclient'));
    const page = await context.newPage();
    const errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto(`${base}/data-status?ticker=005930`);
    assert.equal(await page.getByLabel('기대 시장 기준일 (운영자 확인)').inputValue(), '');
    // Historical comparison reference only; not a claim about today's KRX session.
    await page.getByLabel('기대 시장 기준일 (운영자 확인)').fill('2026-10-02');
    await page.locator('#dataset-cross').getByText('0 달력일', {exact:false}).waitFor();
    await page.getByRole('button',{name:/삼성전자\s*005930 근거 보기/}).click();
    await page.getByRole('heading',{name:'저장 신호',exact:true}).waitFor();
    const source=page.locator('a[href*="rcpNo="]').first();
    const sourceHref=await source.getAttribute('href');
    assert.match(sourceHref, /^https:\/\/dart.fss.or.kr\/dsaf001\/main.do\?rcpNo=\d{14}$/);
    await page.screenshot({path:`${out}/screenshots/${name}-status-full.png`,fullPage:true});
    await page.getByRole('heading',{name:'저장 신호',exact:true}).scrollIntoViewIfNeeded();
    await page.screenshot({path:`${out}/screenshots/${name}-evidence.png`});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.getByRole('searchbox').fill('NO_SUCH_COMPANY');
    await page.getByText('검색 결과 없음',{exact:true}).waitFor();
    await page.locator('#dataset-cross').getByRole('link',{name:'신호 → 종목 → 근거 탐색'}).click();
    assert.equal(await page.getByRole('combobox').inputValue(),'cross');
    await page.getByRole('searchbox').fill('000660');
    await page.getByRole('button',{name:/SK하이닉스\s*000660 근거 보기/}).click();
    await page.getByRole('link',{name:'CROSS 원천 감사'}).click();
    assert.ok(page.url().endsWith('#dataset-cross'));
    await page.locator('#dataset-memberships').getByRole('link',{name:'분류 소속 → 종목 → 근거 탐색'}).click();
    assert.equal(await page.getByRole('combobox').inputValue(),'memberships');
    await page.getByRole('button',{name:/근거 보기$/}).first().click();
    await page.getByText(/JSON Pointer:/).first().waitFor();
    const membership = page.getByRole('link',{name:/ 정원$/}).first();
    const membershipHref = await membership.getAttribute('href');
    await page.screenshot({path:`${out}/screenshots/${name}-membership.png`,fullPage:true});
    await membership.click();
    await page.waitForURL(`**${membershipHref}`);
    await page.getByRole('button',{name:'대시보드 생성하기',exact:true}).waitFor({timeout:60000});
    await page.goto(`${base}/garden/cross_watch`);
    await page.getByRole('button',{name:'대시보드 생성하기',exact:true}).waitFor({timeout:60000});
    const saved=await page.evaluate(()=>localStorage.getItem('kr-garden:gardens'));
    await page.getByRole('button',{name:'대시보드 생성하기',exact:true}).click();
    const dialog=page.getByRole('dialog');
    await dialog.waitFor();
    const summary=await dialog.innerText();
    assert.ok(summary.includes('총평가액'));
    const downloadPromise=page.waitForEvent('download');
    await page.getByRole('button',{name:'MD 전체 다운로드',exact:true}).click();
    const download=await downloadPromise;
    await download.saveAs(`${out}/${name}-cross-dashboard.md`);
    await page.screenshot({path:`${out}/screenshots/${name}-dashboard.png`});
    await dialog.getByRole('link',{name:/데이터 상태\/근거/}).click();
    await page.waitForURL('**/data-status');
    await page.getByRole('heading',{name:'데이터 상태 / 근거'}).waitFor();
    assert.equal(await page.evaluate(()=>localStorage.getItem('kr-garden:gardens')),saved);
    const position=JSON.parse(saved).find(g=>g.id==='cross_watch').positions[0];
    await page.goto(`${base}/garden/cross_watch/plant/${position.id}`);
    const link=page.getByRole('link',{name:/데이터 상태\/근거/});
    await link.waitFor();
    assert.equal(await link.getAttribute('href'),`/data-status?ticker=${position.ticker}`);
    await link.click();
    await page.waitForURL(`**/data-status?ticker=${position.ticker}`);
    assert.equal(await page.getByRole('searchbox').inputValue(),position.ticker);
    assert.deepEqual(errors,[]);
    results.push({viewport:name,passed:true,pageErrors:errors,sourceHref,storedGardenUnchanged:true,mode:'saved prices; API requests blocked; no fabricated data'});
    await context.close();
  }
  writeFileSync(`${out}/browser-smoke.json`,JSON.stringify(results,null,2));
  console.log(JSON.stringify(results,null,2));
} finally { await browser.close(); }
